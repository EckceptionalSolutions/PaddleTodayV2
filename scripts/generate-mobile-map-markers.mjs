import { appendFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { semanticColors } from '../packages/design-tokens/src/index.js';

// Match the 48dp marker frame and its 10dp dot without a native React view
// snapshot for every route. Android selects the matching resource density.
const directory = new URL('../apps/mobile/assets/images/map-dots/', import.meta.url);
await mkdir(directory, { recursive: true });
for (const [name, color] of Object.entries({ strong: semanticColors.rating.strong,
  fair: semanticColors.rating.fair, skip: semanticColors.rating.noGo, unavailable: '#5E685F' })) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><circle cx="24" cy="24" r="4" fill="${color}" stroke="#FFFFFF" stroke-width="2"/></svg>`;
  for (const scale of [1, 2, 3]) {
    const image = await sharp(Buffer.from(svg), { density: 72 * scale }).png().toBuffer();
    await writeFile(new URL(`${name}${scale === 1 ? '' : `@${scale}x`}.png`, directory), image);
  }
}
console.log(`Generated map dot resources in ${fileURLToPath(directory)}`);
const userSvg = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24"><circle cx="12" cy="12" r="11.5" fill="#2F6B59" fill-opacity="0.22" stroke="#FFFFFF" stroke-width="1"/><circle cx="12" cy="12" r="5" fill="#2F6B59"/></svg>';
for (const scale of [1, 2, 3]) {
  await writeFile(new URL(`user${scale === 1 ? '' : `@${scale}x`}.png`, directory),
    await sharp(Buffer.from(userSvg), { density: 72 * scale }).png().toBuffer());
}

// Score badges use the same SDK image path on Android. A few hundred bundled
// glyph images avoid repeatedly rasterizing React border/text views per route.
const scores = new URL('../apps/mobile/assets/images/map-scores/', import.meta.url);
await mkdir(scores, { recursive: true });
const entries = [];
for (const tone of ['strong', 'fair', 'skip', 'unavailable']) {
  entries.push(`  '${tone}:dot': require('../../assets/images/map-dots/${tone}.png'),`);
  const color = { strong: semanticColors.rating.strong, fair: semanticColors.rating.fair,
    skip: semanticColors.rating.noGo, unavailable: '#5E685F' }[tone];
  for (const label of [...Array.from({ length: 101 }, (_, index) => String(index)), '—']) {
    const name = `${tone}-${label === '—' ? 'withheld' : label}`;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><circle cx="24" cy="24" r="17" fill="${color}" stroke="#FFFFFF" stroke-width="2"/><text x="24" y="24" dy="0.35em" text-anchor="middle" font-family="Arial" font-size="11" font-weight="700" fill="#FFFFFF">${label}</text></svg>`;
    for (const scale of [1, 2, 3]) {
      await writeFile(new URL(`${name}${scale === 1 ? '' : `@${scale}x`}.png`, scores),
        await sharp(Buffer.from(svg), { density: 72 * scale }).png().toBuffer());
    }
    entries.push(`  '${tone}:${label}': require('../../assets/images/map-scores/${name}.png'),`);
  }
}
await writeFile(new URL('../apps/mobile/src/lib/android-map-marker-images.android.ts', import.meta.url),
  `// Generated by scripts/generate-mobile-map-markers.mjs.\ndeclare const require: (path: string) => number;\nconst images: Record<string, number> = {\n${entries.join('\n')}\n};\nexport function androidMarkerImage(rating: string | null | undefined, label = 'dot'): number | undefined {\n  const tone = rating === 'stale' || rating === 'unavailable' ? 'unavailable'\n    : rating === 'Strong' || rating === 'Good' ? 'strong' : rating === 'Fair' ? 'fair' : 'skip';\n  return images[tone + ':' + label];\n}\n`);
await appendFile(new URL('../apps/mobile/src/lib/android-map-marker-images.android.ts', import.meta.url),
  "export function androidUserMarkerImage(): number | undefined { return require('../../assets/images/map-dots/user.png'); }\n");
console.log(`Generated Android score resources in ${fileURLToPath(scores)}`);
