function isolateGeometry(decoded, reachId) {
  const marker = `"reachId":"${reachId}","geometry":`;
  const markerIndex = decoded.indexOf(marker);
  if (markerIndex < 0) throw new Error(`Could not find the AW geometry marker for reach ${reachId}.`);
  const geometryStart = decoded.indexOf('{', markerIndex + marker.length);
  let depth = 0;
  let geometryEnd = -1;
  for (let index = geometryStart; index < decoded.length; index += 1) {
    if (decoded[index] === '{') depth += 1;
    if (decoded[index] === '}' && --depth === 0) {
      geometryEnd = index + 1;
      break;
    }
  }
  if (geometryStart < 0 || geometryEnd < 0) throw new Error(`Could not isolate AW geometry for reach ${reachId}.`);
  const geometry = JSON.parse(decoded.slice(geometryStart, geometryEnd));
  if (geometry.type !== 'LineString' || geometry.coordinates.length < 2) {
    throw new Error(`American Whitewater returned unusable geometry for reach ${reachId}.`);
  }
  return geometry.coordinates;
}

const outputDir = path.resolve('public', 'data', 'canonical-river-geometries', 'routes');
await mkdir(outputDir, { recursive: true });

for (const route of routes) {
  let coordinates = route.coordinates ?? (() => {
    if (!route.sourceUrl || !route.reachId) throw new Error(`Curated route ${route.routeId} is missing a source geometry.`);
    return null;
  })();
  let source = 'Curated access-anchor fallback';
  let sourceUrls = [];
  if (!coordinates) {
    const response = await fetch(route.sourceUrl, {
      headers: { 'user-agent': 'PaddleToday canonical route geometry generator' },
    });
    if (!response.ok) throw new Error(`American Whitewater request failed for ${route.reachId} (${response.status}).`);
    sourceUrls = [route.sourceUrl];
    source = 'American Whitewater reach geometry';
    coordinates = isolateGeometry((await response.text()).replaceAll('\\"', '"'), route.reachId);
  }
  const routeCoordinates = [route.putIn, ...coordinates.slice(1, -1), route.takeOut];
  const feature = {
    type: 'Feature',
    properties: {
      routeId: route.routeId,
      riverId: route.riverId,
      name: route.name,
      state: 'New York',
      source,
      ...(sourceUrls.length > 0 ? { sourceUrls } : { traceMode: 'named-fallback' }),
      endpointSnapMaxFeet: 0,
    },
    geometry: {
      type: 'MultiLineString',
      coordinates: [routeCoordinates],
    },
  };
  const outputPath = path.join(outputDir, `${route.routeId}.json`);
  await writeFile(outputPath, `${JSON.stringify(feature)}\n`, 'utf8');
  console.log(`Wrote ${outputPath} with ${routeCoordinates.length} points from ${route.reachId ? `AW reach ${route.reachId}` : 'curated access anchors'}.`);
}
