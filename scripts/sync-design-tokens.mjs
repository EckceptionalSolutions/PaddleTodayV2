import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { semanticColors, semanticRadii, semanticSpacing } from '@paddletoday/design-tokens';

const checkOnly = process.argv.includes('--check');
const targetPath = resolve('public', 'styles', 'semantic-tokens.css');
const generated = `/* Generated by scripts/sync-design-tokens.mjs. Do not edit directly. */
:root {
  --rating-strong: ${semanticColors.rating.strong};
  --rating-good: ${semanticColors.rating.good};
  --rating-fair: ${semanticColors.rating.fair};
  --rating-no-go: ${semanticColors.rating.noGo};
  --status-live: ${semanticColors.status.live};
  --status-degraded: ${semanticColors.status.degraded};
  --status-offline: ${semanticColors.status.offline};
  --radius-control: ${semanticRadii.web.control}px;
  --radius-card: ${semanticRadii.web.card}px;
  --radius-panel: ${semanticRadii.web.panel}px;
  --radius-pill: ${semanticRadii.web.pill}px;
  --space-xs: ${semanticSpacing.web.xs}px;
  --space-sm: ${semanticSpacing.web.sm}px;
  --space-md: ${semanticSpacing.web.md}px;
  --space-lg: ${semanticSpacing.web.lg}px;
  --space-xl: ${semanticSpacing.web.xl}px;
}
`;
const current = await readFile(targetPath, 'utf8').catch(() => null);

if (current === generated) {
  if (checkOnly) {
    console.log('[design-tokens] Generated web semantic tokens are in sync.');
  }
} else if (checkOnly) {
  console.error('[design-tokens] public/styles/semantic-tokens.css is out of sync.');
  console.error('[design-tokens] Run npm run tokens:sync and commit the generated file.');
  process.exitCode = 1;
} else {
  await writeFile(targetPath, generated, 'utf8');
  console.log('[design-tokens] Synced public/styles/semantic-tokens.css.');
}
