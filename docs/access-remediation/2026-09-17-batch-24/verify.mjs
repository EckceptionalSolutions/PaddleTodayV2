import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base='docs/access-remediation/2026-09-17-batch-24/';
const readJson=async(p)=>JSON.parse(await readFile(p,'utf8'));
const selection=await readJson(base+'selection.json');
const review=await readJson(base+'review.json');
const controls=await readJson('src/data/route-access-official-map-controls.json');
const registry=await readJson('src/data/generated/route-access-registry.json');
const holds=await readFile('src/data/generated/withheld-route-slugs.ts','utf8');
const routes=[...new Set(selection.sites.flatMap(s=>s.eligibleUnwithheldRoutes))];
assert.equal(selection.sites.length,4);
assert.deepEqual(selection.sites.map(s=>s.rank),[270,271,274,275]);
assert.deepEqual(selection.skippedPriorSites.map(s=>s.rank),[272,273]);
assert.equal(selection.skippedHeldQueueEntries.length,1);
assert.equal(routes.length,5);
assert.equal(review.sitesReviewed,4);
assert.equal(review.newHolds.length,0);
assert.equal(review.coordinateSitesCorrected,0);
assert.equal(review.withheldRoutesAfter,181);
assert.equal(controls.providers.length,564);
for(const id of ['wi_fox_river_landing_road_access_anchor','wa_haller_park_boat_launch_access_anchor'])assert(controls.providers.some(p=>p.id===id),`missing new provider ${id}`);
for(const id of ['va_south_fork_holston_route58_alvarado_access','ny_ellicott_creek_park_eastern_park_access'])assert.equal(controls.providers.find(p=>p.id===id)?.coordinateRole,'authoritative-access-anchor');
assert.equal(controls.providers.find(p=>p.id==='va_south_fork_holston_route58_alvarado_access').controls.find(c=>c.featureId==='south-fork-holston-alvarado-route710-take-out').name,'Route 710 Alvarado crossing take-out area');
assert.equal(registry.summary.entryCount,4042);
assert.equal(registry.summary.conflictCount,0);
assert.equal(registry.auditGeneratedAt,selection.audit.generatedAt);
assert.equal((holds.match(/"[a-z0-9-]+"/g)||[]).length,181);
const va=await readFile('src/data/routes/virginia.ts','utf8');assert(va.includes("name: 'Route 710 Alvarado crossing take-out area'"));assert(va.includes('primitive public bridge-crossing access-area anchor'));
const wi=await readFile('src/data/routes/wisconsin.ts','utf8');assert(wi.includes('Fox River Landing Road public access-area anchor'));assert(wi.includes('does not publish a surveyed water-entry edge'));
const wa=await readFile('src/data/routes/washington-stillaguamish.ts','utf8');assert(wa.includes('Haller Park boat-launch access-area anchor'));assert(wa.includes('not a surveyed ramp toe'));
console.log(`Batch 24 verified: ${selection.sites.length} remaining eligible sites, ${routes.length} routes, two new controls, no coordinate moves, and no new route holds.`);
