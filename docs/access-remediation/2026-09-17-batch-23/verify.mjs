import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base='docs/access-remediation/2026-09-17-batch-23/';
const readJson=async(path)=>JSON.parse(await readFile(path,'utf8'));
const selection=await readJson(base+'selection.json');
const review=await readJson(base+'review.json');
const controls=await readJson('src/data/route-access-official-map-controls.json');
const registry=await readJson('src/data/generated/route-access-registry.json');
const manifest=await readFile('src/data/generated/withheld-route-slugs.ts','utf8');
const holds=await readFile('src/data/route-access-review-holds.ts','utf8');
const routes=[...new Set(selection.sites.flatMap(s=>s.eligibleUnwithheldRoutes))];
assert.equal(selection.sites.length,10);
assert.deepEqual(selection.sites.map(s=>s.rank),[258,259,260,261,263,264,265,266,268,269]);
assert.equal(routes.length,20);
assert.equal(review.sitesReviewed,10);
assert.equal(review.uniqueRoutesBefore,20);
assert.equal(review.coordinateSitesCorrected,1);
assert.equal(review.withheldRoutesAfter,181);
assert.equal(controls.providers.length,562);
for(const id of ['pa_ohiopyle_ramcat_launch_access_anchor','fl_peacock_slough_river_camp_access_anchor']) assert(controls.providers.some(p=>p.id===id),`missing provider ${id}`);
const ramcat=controls.providers.find(p=>p.id==='pa_ohiopyle_ramcat_launch_access_anchor');
assert.equal(ramcat.sourceDocumentDate,null);
assert.equal(ramcat.controls[0].latitude,39.82632);
const peacock=controls.providers.find(p=>p.id==='fl_peacock_slough_river_camp_access_anchor');
assert.equal(peacock.controls[0].longitude,-83.137167);
for(const id of review.newHolds){assert(holds.includes(id),`missing source hold ${id}`);assert(manifest.includes(id),`missing generated hold ${id}`);}
assert.equal(registry.summary.entryCount,4042);
assert.equal(registry.summary.conflictCount,0);
assert.equal(registry.auditGeneratedAt,selection.audit.generatedAt);
const florida=await readFile('src/data/routes/florida-suwannee.ts','utf8');
assert(florida.includes('latitude: 30.1015, longitude: -83.137167'));
assert(florida.includes('Peacock Slough River Camp access-area anchor'));
const idaho=await readFile('src/data/routes/idaho.ts','utf8');
assert(idaho.includes('Concrete CCC Bridge access area (public river entry unverified)'));
assert(idaho.includes('Meadow Creek Campground access (current landing unverified)'));
const sc=await readFile('src/data/routes/south-carolina-catawba.ts','utf8');
assert(sc.includes('Rock Hill River Park canoe/kayak launch access-area anchor'));
console.log(`Batch 23 verified: 10 sites, ${routes.length} selected routes, ${review.newHolds.length} new holds, one coordinate correction, two provider controls, and a 4042-entry zero-conflict registry.`);
