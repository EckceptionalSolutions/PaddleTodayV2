type NorthCarolinaBluewayRouteSpec = {
  id: string;
  riverId: string;
  name: string;
  reach: string;
  aliases: string[];
  region: string;
  summary: string;
  statusText: string;
  putIn: { name: string; latitude: number; longitude: number };
  takeOut: { name: string; latitude: number; longitude: number };
  distanceMiles: number;
  paddleTime: string;
  midpoint: { latitude: number; longitude: number };
  gaugeSiteId: string;
  gaugeSiteName: string;
  gaugeKind: 'direct' | 'proxy';
  gaugeDetailUrl: string;
  gaugeHydrographUrl: string;
  thresholdSource: { label: string; url: string };
  accessEvidence: string;
  camping: string;
  campingClassification: 'endpoint_campground' | 'on_route_campsite' | 'nearby_basecamp' | 'none';
  campingHazard: string;
  difficulty: 'easy' | 'moderate' | 'hard';
  difficultyNotes: string;
  seasonNotes: string;
  safetyNotes: string[];
  sourceLinks: River['sourceLinks'];
};

function buildNorthCarolinaBluewayRoute(spec: NorthCarolinaBluewayRouteSpec): River {
  const routeLabel = `${spec.putIn.name} to ${spec.takeOut.name}`;
  const gaugeKindLabel = spec.gaugeKind === 'direct' ? 'direct' : 'same-river proxy';

  return {
    id: spec.id,
    riverId: spec.riverId,
    slug: spec.id,
    name: spec.name,
    reach: spec.reach,
    aliases: spec.aliases,
    state: 'North Carolina',
    region: spec.region,
    routeType: 'recreational',
    summary: spec.summary,
    statusText: `${spec.statusText} The route is planning-only: use the ${gaugeKindLabel} USGS station with recent rain, trend, visual channel, debris, temperature, daylight, and current access notices; no numeric recreational cutoff is transferred.`,
    latitude: spec.midpoint.latitude,
    longitude: spec.midpoint.longitude,
    safetyProfile: {
      riskLevel: 'caution',
      hazards: ['low_water', 'fast_rise', 'strainers', 'cold_water', 'access_uncertain', 'mandatory_takeout', 'dam'],
      safetyNotes: spec.safetyNotes,
      reviewStatus: 'reviewed',
    },
    gaugeSource: {
      id: `usgs-${spec.gaugeSiteId}`,
      provider: 'usgs',
      siteId: spec.gaugeSiteId,
      metric: 'discharge_cfs',
      unit: 'cfs',
      kind: spec.gaugeKind,
      siteName: spec.gaugeSiteName,
      detailUrl: spec.gaugeDetailUrl,
      hydrographUrl: spec.gaugeHydrographUrl,
    },
    profile: {
      thresholdModel: 'minimum-only',
      thresholdSource: { label: spec.thresholdSource.label, url: spec.thresholdSource.url, provider: 'local' },
      thresholdSourceStrength: 'official',
      rainfallSensitivity: 'high',
      seasonMonths: [3, 4, 5, 6, 7, 8, 9, 10],
      seasonNotes: spec.seasonNotes,
      difficulty: spec.difficulty,
      difficultyNotes: spec.difficultyNotes,
      confidenceNotes: `High confidence in the named access pair and published corridor description. The ${gaugeKindLabel} USGS station is retained for current context only; no threshold is inferred from it.`,
    },
    putIn: spec.putIn,
    takeOut: spec.takeOut,
    accessPoints: [
      {
        id: `${spec.id}-put-in`,
        name: spec.putIn.name,
        latitude: spec.putIn.latitude,
        longitude: spec.putIn.longitude,
        mileFromStart: 0,
        segmentKind: 'transition',
        note: 'The cited corridor source identifies this as a public or managed paddle access. Confirm current parking, carry, waterline, hours, and closure notices before unloading.',
      },
      {
        id: `${spec.id}-take-out`,
        name: spec.takeOut.name,
        latitude: spec.takeOut.latitude,
        longitude: spec.takeOut.longitude,
        mileFromStart: spec.distanceMiles,
        segmentKind: 'transition',
        note: 'Use only the named endpoint and its lawful landing. Confirm current footing, parking, carry, hours, and downstream hazards before committing to the take-out.',
      },
    ],
    logistics: {
      distanceLabel: `approximately ${spec.distanceMiles} river miles`,
      estimatedPaddleTime: spec.paddleTime,
      shuttle: `Stage the downstream vehicle at ${spec.takeOut.name}, then shuttle to ${spec.putIn.name}. Verify current road access, parking, carry, landing, and any pass or reservation requirement before launch.`,
      permits: 'Follow North Carolina boating and PFD rules, all access-manager hours and closures, posted dam or portage controls, and any pass or reservation terms. No route-specific paddling permit is implied beyond the access terms cited here.',
      camping: spec.camping,
      campingClassification: spec.campingClassification,
      summary: spec.summary,
      accessCaveats: [
        spec.accessEvidence,
        'Published access information does not guarantee a clear waterline, safe landing, parking availability, or current post-storm conditions. Recheck the managing agency and on-site signs before unloading.',
        'Do not use a bridge shoulder, private bank, dam apron, or informal shoreline as a substitute endpoint.',
      ],
      watchFor: ['USGS current trend and recent rain', 'low-water rocks and scraping', 'fast rises and storm debris', 'strainers and cold water', 'dam or mandatory portage', 'access hours, parking, and carry', 'private banks and missed take-out', spec.campingHazard],
    },
    evidenceNotes: [
      { label: 'Named public endpoint pair', value: routeLabel, note: spec.accessEvidence, sourceUrl: spec.thresholdSource.url },
      { label: 'Published route length and paddling context', value: `${spec.distanceMiles} miles; ${spec.paddleTime}`, note: 'The cited blueway or park material provides the corridor distance or access-chain context; this remains a planning estimate, not a guaranteed travel time.', sourceUrl: spec.thresholdSource.url },
      { label: `${gaugeKindLabel} gauge context`, value: `USGS ${spec.gaugeSiteId} ${spec.gaugeSiteName}`, note: 'Use current discharge, stage, trend, recent rainfall, and visual conditions. No numeric recreational cutoff is transferred.', sourceUrl: spec.gaugeDetailUrl },
      { label: 'Camping posture', value: spec.campingClassification, note: spec.campingHazard, sourceUrl: spec.thresholdSource.url },
      { label: 'Safety and boundary posture', value: 'Planning-only moving-water route with explicit access and hazard checks', note: spec.safetyNotes.join(' ') },
    ],
    sourceLinks: spec.sourceLinks,
    scoreEligibility: 'planning',
    ...(spec.gaugeKind === 'proxy' ? { scoreEligibilityReason: 'proxy_gauge' as const } : {}),
  };
}

